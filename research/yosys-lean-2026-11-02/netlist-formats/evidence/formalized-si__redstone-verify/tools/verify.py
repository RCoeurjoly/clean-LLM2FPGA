# x / 0 and x % 0 are x in Verilog, but Yosys' lowering (and its SAT model) gives them a fixed
# value. This techmap rule makes the result x whenever the divisor is 0, so that setundef frees it
# like any other x; the operation itself is parked in a $__rsv_<op> cell that `chtype` turns back
# into $<op> for the ordinary techmap.
DIVZERO_MAP = r"""(* techmap_celltype = "$div $mod $divfloor $modfloor" *)
module _rsv_divzero (A, B, Y);
  parameter A_SIGNED = 0, B_SIGNED = 0, A_WIDTH = 1, B_WIDTH = 1, Y_WIDTH = 1;
  parameter _TECHMAP_CELLTYPE_ = "";
  input [A_WIDTH-1:0] A;
  input [B_WIDTH-1:0] B;
  output [Y_WIDTH-1:0] Y;
  wire [Y_WIDTH-1:0] q;
  generate
    if (_TECHMAP_CELLTYPE_ == "$div") \$__rsv_div #(.A_SIGNED(A_SIGNED), .B_SIGNED(B_SIGNED),
      .A_WIDTH(A_WIDTH), .B_WIDTH(B_WIDTH), .Y_WIDTH(Y_WIDTH)) op (.A(A), .B(B), .Y(q));
    if (_TECHMAP_CELLTYPE_ == "$mod") \$__rsv_mod #(.A_SIGNED(A_SIGNED), .B_SIGNED(B_SIGNED),
      .A_WIDTH(A_WIDTH), .B_WIDTH(B_WIDTH), .Y_WIDTH(Y_WIDTH)) op (.A(A), .B(B), .Y(q));
    if (_TECHMAP_CELLTYPE_ == "$divfloor") \$__rsv_divfloor #(.A_SIGNED(A_SIGNED), .B_SIGNED(B_SIGNED),
      .A_WIDTH(A_WIDTH), .B_WIDTH(B_WIDTH), .Y_WIDTH(Y_WIDTH)) op (.A(A), .B(B), .Y(q));
    if (_TECHMAP_CELLTYPE_ == "$modfloor") \$__rsv_modfloor #(.A_SIGNED(A_SIGNED), .B_SIGNED(B_SIGNED),
      .A_WIDTH(A_WIDTH), .B_WIDTH(B_WIDTH), .Y_WIDTH(Y_WIDTH)) op (.A(A), .B(B), .Y(q));
  endgenerate
  assign Y = B == 0 ? {Y_WIDTH{1'bx}} : q;
endmodule
"""
# Certify: the miter as a plain AIG, with NO optimisation pass, so that the SAT solver (whose
# proof is checked) decides the miter and not a trusted optimiser. Run with cwd = work dir:
# relative names keep the script, and hence its hash, independent of where the directory is.
#   hierarchy, proc -noopt, flatten : elaborate the three modules into one flat netlist
#   techmap -map divzero_map.v, chtype : a zero divisor gives x (see DIVZERO_MAP)
#   setundef          : x constants and undriven bits become $anyseq, i.e. free AIG inputs (as in
#                       the prove stage); the second run (x constants only) catches x made by the
#                       lowering itself, e.g. out-of-range $shiftx (write_aiger refuses any x left)
#   techmap, aigmap   : word-level cells -> gates -> AND/NOT only (write_aiger accepts nothing else)
#   check -assert     : no logic loop and no multiple drivers, so the AIG is a function of its inputs
AIGER_SCRIPT = f"""read_verilog -sv {SPEC_COPY}
read_verilog -sv impl.v
read_verilog -sv miter.v
hierarchy -check -top _rsv_miter
proc -noopt
flatten
techmap -map divzero_map.v
chtype -map $__rsv_div $div
chtype -map $__rsv_mod $mod
chtype -map $__rsv_divfloor $divfloor
chtype -map $__rsv_modfloor $modfloor
setundef -undriven -anyseq
techmap
setundef -anyseq
aigmap
check -assert
write_aiger -ascii -symbols miter.aag
"""


