#!/usr/bin/env python3
"""Verification funnel for one redstone candidate.

  verify.py --spec circuits/xor/spec.v --top xor2 circuits/xor/cand.rsl [--seed seed.rsl] [--json out.json]

Stages (a candidate is ACCEPTED only if all pass):
  1. extract   : layout -> MCHPRS world -> redpiler graph (rsv graph); unbuildable layouts
                 (floating wires, torches without a block, duplicate port names) are rejected
  2. subset    : graph is in the supported combinational subset (tools/graph2v.py)
  3. ports     : spec ports (read by Yosys) are 1-bit, not reserved, and match the levers/lamps
  4. prove     : Yosys miter spec <-> model, SAT proof of equivalence for ALL inputs
  5. certify   : miter -> AIGER without optimisation passes (Yosys) -> CNF by a plain Tseitin
                 encoder (tools/aig2cnf.py); CaDiCaL writes an LRAT proof of UNSAT, which
                 rup_check (tools/check_cert.py), lrat-check and the verified cake_lpr
                 (required: `make cake_lpr`) must all accept; certificate.json binds the sha256 of every file from
                 the layout to the proof (re-check: tools/check_cert.py DIR; docs/CERTIFICATE.md)
  6. lean      : the same claim proved in Lean 4 on an independent route: tools/v2lean.py turns
                 the spec (Yosys AIG, same reading as certify) into a Lean `Spec`, graph2lean.py
                 turns graph.json into a Lean `Layout`, and `lake env lean` must prove
                 `Implements layout spec` (lean/Redstone/Cert.lean). Route "kernel" (decide +kernel
                 over all inputs, axioms propext/Quot.sound only) for <= 8 inputs and a spec without
                 undefined values, else "bv_decide" (adds bv_decide's native-code axiom); the route
                 and the axioms are recorded in the report and in certificate.json
  7. cosim     : run on the MCHPRS vanilla-port engine AND on redpiler (`rsv cosim`): all 2^n
                 vectors up to 16 inputs; above that, the 2n+2 structured vectors (all-zero,
                 all-one, walking one, walking zero) followed by 4096 fixed pseudo-random ones,
                 without duplicates. Both engines must equal the model (checks the formal model
                 against the engine), equal the spec, and settle (no oscillation) within --max-ticks
  8. metrics   : blocks, volume, components, critical path, settle ticks, glitches

Undefined values in the spec (x, undriven nets) are treated as unconstrained: the proof must
hold for every value they take, so an `x` is never a don't-care.

The layout and the spec are copied into the work directory first (input.rsl, input_spec.v) and
every stage reads the copies, so the hashes in certificate.json are of the bytes that were checked.
"""
