def lift_lean_limits(text):
    """The cert.lean text with Lean's resource limits lifted (same statement, same tactics; see docs/DECISIONS.md)."""
    text = text.replace("set_option maxHeartbeats 4000000", "set_option maxHeartbeats 0")
    text = text.replace("  simp only [rs_simp, layout,", "  simp (config := { maxSteps := 1000000000 }) only [rs_simp, layout,")
    text = text.replace("bv_decide (config := { timeout := 600,", "bv_decide (config := { timeout := 3600, maxSteps := 1000000000,")
    text = text.replace("\n  bv_decide\n", "\n  bv_decide (config := { timeout := 3600, maxSteps := 1000000000 })\n")   # bv_decide runs its own simp with its own step limit
    return text


def lean_stage(work, top, n_inputs):
    """Stage 6 -> (ok, msg, info). Independent of the Yosys miter and of graph2v.py: the spec
    goes through tools/v2lean.py, the graph through tools/graph2lean.py, and Lean's kernel checks
    `Implements layout spec`. Output files are deleted first, so only this run's files are read."""
    P = lambda f: os.path.join(work, f)
    for f in ("spec.lean", "cert.lean", "lean.log"):
        if os.path.exists(P(f)):
            os.remove(P(f))
    shutil.rmtree(P("v2lean"), ignore_errors=True)
    info = {}
    r = run([sys.executable, os.path.join(ROOT, "tools", "v2lean.py"), SPEC_COPY, "--top", top, "--no-header",
             "--ns", f"V2L.«{top}»", "--work", "v2lean", "--source", SPEC_COPY, "-o", "spec.lean"], cwd=work)
    if r.returncode or not os.path.isfile(P("spec.lean")):
        return False, "v2lean: " + (r.stderr.strip().splitlines() or [f"rc={r.returncode}"])[-1][:300], info
    text = open(P("spec.lean")).read()
    m = re.search(r"AIG: (\d+) port inputs, (\d+) free inputs, (\d+) AND gates", text)
    info["spec"] = {"port_inputs": int(m.group(1)), "free_inputs": int(m.group(2)), "and_gates": int(m.group(3))}
    route = "kernel" if n_inputs <= LEAN_KERNEL_MAX and "theorem spec_local" in text else "bv_decide"
    info["route"] = route
    r = run([sys.executable, os.path.join(ROOT, "tools", "graph2lean.py"), "graph.json", "--spec", "v2lean",
             "--spec-ref", f"V2L.«{top}».spec", "--name", "cert", "--source", LAYOUT_COPY, "--prelude", "spec.lean",
             "--route", route, "--print-axioms", "-o", "cert.lean"], cwd=work)
    if r.returncode or not os.path.isfile(P("cert.lean")):
        return False, f"graph2lean exit {r.returncode}: " + r.stderr.strip()[-300:], info
    try:
        r = run(["lake", "build", "Redstone"], cwd=LEAN_DIR)
    except OSError as e:
        return False, f"cannot run lake: {e}", info
    if r.returncode:
        return False, "lake build Redstone failed: " + (r.stdout + r.stderr).strip()[-300:], info
    if LEAN_LONG:
        orig = open(P("cert.lean")).read()
        lifted = lift_lean_limits(orig)                          # read before the file is opened for writing
        if not lifted.strip() or lifted == orig:
            return False, "--lean-long: no Lean limit to lift in cert.lean", info
        open(P("cert.lean"), "w").write(lifted)
        info["limits_lifted"] = True
    t0 = time.perf_counter()
    try:
        r = run(["lake", "env", "lean", P("cert.lean")], cwd=LEAN_DIR, timeout=LEAN_TIMEOUT)
        out, rc = r.stdout + r.stderr, r.returncode
    except subprocess.TimeoutExpired:
        out, rc = f"timeout after {LEAN_TIMEOUT} s", -1
    info["lean_s"] = round(time.perf_counter() - t0, 3)
    info["timeout_s"] = LEAN_TIMEOUT
    open(P("lean.log"), "w").write(out)
    info["sha256"] = {f: sha256(P(f)) for f in ("spec.lean", "cert.lean")}
    ax = re.search(r"'Generated\.cert\.certified' depends on axioms: \[([^\]]*)\]", out)
    axioms = [x.strip() for x in ax.group(1).split(",")] if ax else None
    info["axioms"] = axioms
    errors = [l for l in out.splitlines() if ": error" in l or l.startswith("error")]
    if rc == 0 and not errors and axioms is not None and "sorryAx" not in axioms and "sorry" not in out:
        native = [x for x in axioms if "_native" in x or "ofReduceBool" in x]
        if route == "kernel" and native:
            return False, f"kernel route depends on native axioms {native}", info
        return True, f"PROVED ({route} route; axioms: {', '.join(axioms)})", info
    cex = {int(k): v == "true" for k, v in re.findall(r"^x (\d+) = (true|false)$", out, re.M)}
    if cex:
        info["counterexample"] = cex
    why = (errors[0] if errors else out.strip().splitlines()[-1] if out.strip() else f"rc={rc}")
    why = why.replace(P("cert.lean"), "cert.lean")[:200]
    return False, f"NOT PROVED ({route} route): " + why, info


def spec_ports(spec, top, work):
    """Ports of `top` as Yosys elaborates them: ({name: (direction, width)}, sequential cells or None)."""
    pj = os.path.join(work, "ports.json")
    ys = os.path.join(work, "ports.ys")
    open(ys, "w").write(f"read_verilog -sv {spec}\nhierarchy -top {top}\nproc\nflatten\n"
                        f"write_json {pj}\nselect -assert-none {SEQ_CELLS}\n")
    r = run(["yosys", "-q", "-l", os.path.join(work, "ports.log"), ys])
    if not os.path.exists(pj):
        err = [l for l in (r.stdout + r.stderr).splitlines() if "ERROR" in l]
        return None, (err[0] if err else f"yosys rc={r.returncode}")
    try:
        mods = json.load(open(pj))["modules"]
    except ValueError:
        return None, "yosys wrote no port list"
    ports = {k: (v["direction"], len(v["bits"])) for k, v in mods[top]["ports"].items()}
    seq = None
    if r.returncode:
        log = open(os.path.join(work, "ports.log")).read()
        seq = "sequential spec (flip-flops or latches): " + ", ".join(
            re.findall(r"^\S+/(\S+)$", log, re.M)[:4]) if "Assertion failed" in log else \
            next((l for l in log.splitlines() if "ERROR" in l), f"yosys rc={r.returncode}")
    return ports, seq


def simulate(verilog_files, top, ins, outs, work, vectors):
    """Simulate `top` with Icarus Verilog -> {vector: {out: 0/1/None}}; None = x or z."""
    vec = os.path.join(work, f"vectors_{top}.hex")
    open(vec, "w").write("\n".join(f"{v:x}" for v in vectors) + "\n")
    w = max(len(ins), 1)
    tb = os.path.join(work, f"tb_{top}.v")
    with open(tb, "w") as f:
        f.write(f"module tb; reg [{w-1}:0] mem [0:{len(vectors)-1}]; reg [{w-1}:0] v; integer i;\n")
        for o in outs:
            f.write(f"  wire {o};\n")
        conn = ", ".join([f".{p}(v[{k}])" for k, p in enumerate(ins)] + [f".{o}({o})" for o in outs])
        f.write(f"  {top} dut({conn});\n")
        fmt = " ".join(["%0d"] * len(outs))
        f.write(f"  initial begin $readmemh(\"{vec}\", mem); for (i = 0; i < {len(vectors)}; i = i + 1) "
                f"begin v = mem[i]; #1 $display(\"%0d {fmt}\", v, {', '.join(outs)}); end end\nendmodule\n")
    exe = os.path.join(work, f"sim_{top}")
    r = run(["iverilog", "-g2012", "-o", exe, tb] + verilog_files)
    if r.returncode:
        raise SimError("iverilog failed: " + r.stderr.strip()[-300:])
    # A spec with a combinational loop can oscillate forever on some vector (tests/adversarial/loop_spec.v
    # does on all-one): bound the run so that the funnel reports it instead of hanging.
    limit = SIM_TIMEOUT_S + SIM_TIMEOUT_PER_VECTOR_S * len(vectors)
    try:
        r = run(["vvp", "-n", exe], timeout=limit)
    except subprocess.TimeoutExpired:
        raise SimError(f"simulation of {top} did not finish within {limit:.0f} s "
                       "(a combinational loop that oscillates on some vector?)")
    table = {}
    for line in r.stdout.strip().splitlines():
        xs = line.split()
        table[int(xs[0])] = {o: (int(v) if v.isdigit() else None) for o, v in zip(outs, xs[1:])}
    if len(table) != len(set(vectors)):
        raise SimError(f"simulation of {top} returned {len(table)} of {len(set(vectors))} vectors")
    return table


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("layout")
    ap.add_argument("--spec", required=True)
    ap.add_argument("--top", required=True)
    ap.add_argument("--seed", help="seed layout, to report improvement")
    ap.add_argument("--max-ticks", type=int, default=200)
    ap.add_argument("--json")
    ap.add_argument("--keep", help="directory to keep generated files")
    ap.add_argument("--lean-long", action="store_true",
                    help="lift Lean's resource limits (simp maxSteps, maxHeartbeats, bv_decide's SAT timeout and its own simp maxSteps) in the lean stage; "
                         "the report marks the stage limits_lifted. Same statement, same tactics; for layouts whose default run "
                         "ends in a resource-limit error.")
    ap.add_argument("--certify-only", action="store_true",
                    help="run stages 1-5 only (extract .. certify), for tools/cert_bundle.py: no lean, cosim or "
                         "metrics. An accepted run ends with the verdict PROOF-ACCEPT, never ACCEPT, and "
                         "certificate.json lists the skipped stages. Default behaviour is unchanged.")
    a = ap.parse_args()
    global LEAN_LONG
    LEAN_LONG = a.lean_long

    # Read the inputs once, before clean() (which could remove them if they live in the work dir);
    # every stage then reads the copies in the work dir.
    def slurp(p):
        try:
            with open(p, "rb") as f:
                return f.read()
        except OSError as e:
            return e
    layout_bytes, spec_bytes = slurp(a.layout), slurp(a.spec)
    work = os.path.abspath(a.keep or tempfile.mkdtemp(prefix="rsv_"))
    os.makedirs(work, exist_ok=True)
    clean(work)
    layout, spec = os.path.join(work, LAYOUT_COPY), os.path.join(work, SPEC_COPY)
    rep = {"layout": a.layout, "spec": a.spec, "stages": {}}
    verdict = "ACCEPT"
    cert = None
    t0 = [time.perf_counter()]

    def stage(name, ok, **info):
        nonlocal verdict
        now = time.perf_counter()
        rep["stages"][name] = {"ok": ok, **info, "time_s": round(now - t0[0], 4)}
        t0[0] = now
        print(f"  [{'ok' if ok else 'FAIL'}] {name}" + (f"  {info.get('msg','')}" if info.get("msg") else ""))
        if not ok:
            verdict = "REJECT"
        return ok

    def finish():
        nonlocal verdict
        if a.certify_only and verdict == "ACCEPT":
            verdict = "PROOF-ACCEPT"        # lean and cosim did not run: not a funnel ACCEPT
        rep["verdict"] = verdict
        if a.certify_only:
            rep["skipped_stages"] = ["lean", "cosim_redstone", "cosim_redpiler", "metrics"]
        if cert is not None:
            if "lean" in rep["stages"]:
                ls = rep["stages"]["lean"]
                cert["lean"] = {"proved": ls["ok"], "route": ls.get("route"), "axioms": ls.get("axioms"),
                                "theorem": "Generated.cert.certified : Implements layout V2L.<top>.spec",
                                "files_sha256": ls.get("sha256"), "spec": ls.get("spec"),
                                "check": "cd lean && lake env lean <work>/cert.lean"}
            cert["funnel"] = {"verdict": verdict, "stages_ok": {k: v["ok"] for k, v in rep["stages"].items()},
                              "layout": a.layout, "spec": a.spec, "work": os.path.abspath(work)}
            if a.certify_only:
                cert["funnel"]["skipped_stages"] = rep["skipped_stages"]
            cp = os.path.join(work, "certificate.json")
            json.dump(cert, open(cp, "w"), indent=1)
            rep["certificate"] = {"file": os.path.abspath(cp), "sha256": sha256(cp), "verdict": "VERIFIED",
                                  "aig": cert["aig"], "cnf": cert["cnf"], "lrat": cert["lrat"],
                                  "lean": cert.get("lean"),
                                  "trivial": cert["trivial"], "files_sha256": cert["sha256"]}
        print(f"== {verdict}: {a.layout}")
        if a.json:
            json.dump(rep, open(a.json, "w"), indent=2)
        sys.exit(0 if verdict in ("ACCEPT", "PROOF-ACCEPT") else 1)

    print(f"== {a.layout}")
    # 1. extract
    gpath, vpath, mpath = (os.path.join(work, x) for x in ("graph.json", "impl.v", "meta.json"))
    if isinstance(layout_bytes, OSError):
        stage("extract", False, msg=f"cannot read layout: {layout_bytes}")
        finish()
    open(layout, "wb").write(layout_bytes)
    r = run([RSV, "graph", layout])
    if r.returncode:
        stage("extract", False, msg=r.stderr.strip()[-600:])
        finish()
    open(gpath, "w").write(r.stdout)
    graph = json.loads(r.stdout)
    stats = json.loads(run([RSV, "stats", layout]).stdout)
    stage("extract", True, msg=f"{len(graph['nodes'])} graph nodes")

    # 2. subset + model (relative names: impl.v then does not depend on where the work dir is)
    r = run([sys.executable, os.path.join(ROOT, "tools", "graph2v.py"), "graph.json", "rs_impl", "meta.json"], cwd=work)
    if r.returncode:
        stage("subset", False, msg=r.stderr.strip())
        finish()
    open(vpath, "w").write(r.stdout)
    meta = json.load(open(mpath))
    stage("subset", True, msg="combinational, supported components")

    # 3. ports: spec interface as elaborated by Yosys vs levers/lamps of the layout
    mins, mouts = graph["inputs"], graph["outputs"]
    if isinstance(spec_bytes, OSError):
        stage("ports", False, msg=f"cannot read spec: {spec_bytes}")
        finish()
    open(spec, "wb").write(spec_bytes)
    sp, seq = spec_ports(spec, a.top, work)
    if sp is None:
        stage("ports", False, msg=f"cannot elaborate spec: {seq}")
        finish()
    ins = [p for p, (d, _) in sp.items() if d == "input"]
    outs = [p for p, (d, _) in sp.items() if d == "output"]
    problems = [f"{p} is {d} [{w}]" for p, (d, w) in sp.items() if w != 1 or d not in ("input", "output")]
    problems += [f"reserved name {p}" for p in sorted(set(sp) | set(mins) | set(mouts)) if RESERVED.search(p)]
    if RESERVED.search(a.top):
        problems.append(f"reserved module name {a.top}")
    if seq:
        problems.append(seq)
    if sorted(ins) != sorted(mins) or sorted(outs) != sorted(mouts):
        problems.append(f"spec {ins}->{outs} vs layout levers {mins} lamps {mouts}")
    if problems:
        stage("ports", False, msg="; ".join(problems))
        finish()
    stage("ports", True, msg=f"{len(ins)} inputs, {len(outs)} outputs, all 1-bit")

    # 4. prove (Yosys SAT on the miter). Internal names carry the reserved _rsv_ prefix.
    ys = os.path.join(work, "equiv.ys")
    mv = os.path.join(work, "miter.v")
    open(mv, "w").write(miter_text(a.top, ins, outs))
    prelude = f"""read_verilog -sv {spec}
read_verilog -sv {vpath}
read_verilog -sv {mv}
prep -top _rsv_miter -flatten
setundef -undriven -anyseq
opt -fast
"""
    open(ys, "w").write(prelude + "sat -verify -prove _rsv_bad 0 -show-inputs _rsv_miter\n")
    r = run(["yosys", "-q", "-e", FATAL_WARNINGS, "-l", os.path.join(work, "yosys.log"), ys])
    log = open(os.path.join(work, "yosys.log")).read()
    if r.returncode == 0 and "SUCCESS!" in log:
        stage("prove", True, msg="SAT: miter output unreachable for all inputs")
    elif "model found: FAIL!" not in log:
        err = next((l for l in log.splitlines() if "ERROR" in l), f"yosys rc={r.returncode}")
        stage("prove", False, msg=f"yosys error: {err.strip()}")
    else:
        cex = re.findall(r"^\s*\\(\w+)\s+\d+\s+\S+\s+([01]+)\s*$", log, re.M)
        cexd = {k: int(v) for k, v in cex if k in ins}
        stage("prove", False, msg="counterexample: " + (", ".join(f"{k}={v}" for k, v in cexd.items() if v) or "all inputs 0"),
              counterexample=cexd)
        # replay the counterexample on the real engine
        bits = sum(cexd.get(p, 0) << k for k, p in enumerate(mins))
        rr = run([RSV, "cosim", layout, "--vectors", str(bits)])
        if rr.returncode == 0:
            eng = json.loads(rr.stdout)["rows"][0]["out"]
            try:
                spv = simulate([spec], a.top, mins, mouts, work, [bits])[bits]
            except SimError as e:
                spv = str(e)
            rep["stages"]["prove"]["replay"] = {"engine": eng, "spec": spv}
            print(f"         replay on MCHPRS engine: engine {eng} vs spec {spv}")

    # 5. certify: unoptimised AIGER -> Tseitin CNF -> CaDiCaL LRAT -> proof checkers (see certify())
    ok, msg, info, cert = certify(work, a.top, ins, outs, {LAYOUT_COPY: hashlib.sha256(layout_bytes).hexdigest(),
                                                           SPEC_COPY: hashlib.sha256(spec_bytes).hexdigest()})
    stage("certify", ok, msg=msg, **info)

    if a.certify_only:
        finish()

    # 6. lean: independent proof of the same claim in Lean (see lean_stage())
    ok, msg, lean_info = lean_stage(work, a.top, len(ins))
    if "counterexample" in lean_info:
        cx = lean_info["counterexample"]
        on = [p for k, p in enumerate(mins) if cx.get(k)]
        msg += "; counterexample: " + (", ".join(f"{p}=1" for p in on) or "all inputs 0")
        lean_info["counterexample"] = {p: int(cx.get(k, False)) for k, p in enumerate(mins)}
        free = {k - len(mins): int(v) for k, v in cx.items() if k >= len(mins)}
        if free:   # values of the spec's undefined bits (x, undriven, x / 0) in the counterexample
            lean_info["counterexample_undefined_bits"] = free
    stage("lean", ok, msg=msg, **lean_info)

    # 7. cosim against the engine: engine == model (semantics check) and engine == spec (defence in depth)
    cos, spec_sims = {}, {}      # spec_sims: the spec's table per vector set, shared by both backends
    for be in ("redstone", "redpiler"):
        r = run([RSV, "cosim", layout, "--backend", be, "--max-ticks", str(a.max_ticks)])
        if r.returncode:
            stage(f"cosim_{be}", False, msg=r.stderr.strip()[-200:])
            continue
        c = json.loads(r.stdout)
        cos[be] = c
        vectors = [row["in"] for row in c["rows"]]
        try:
            model = simulate([vpath], "rs_impl", mins, mouts, work, vectors)
            key = tuple(vectors)
            if key not in spec_sims:
                try:
                    spec_sims[key] = simulate([spec], a.top, mins, mouts, work, vectors)
                except SimError as e:
                    spec_sims[key] = e
            if isinstance(spec_sims[key], SimError):
                raise spec_sims[key]
            spec_tab = spec_sims[key]
        except SimError as e:
            stage(f"cosim_{be}", False, msg=str(e))
            continue
        bad = [row for row in c["rows"] if row["out"] != model[row["in"]]]
        loud = [row for row in c["rows"] if not row["quiet"]]
        spec_bad = [row for row in c["rows"] if row["out"] != spec_tab[row["in"]]]
        ok = not bad and not loud and not spec_bad
        exhaustive = c.get("exhaustive", True)
        nstruct, nrand = c.get("structured", 0), c.get("random", 0)
        kind = "exhaustive" if exhaustive else f"({nstruct} structured + {nrand} random)" if nstruct else "random"
        msg = (f"{len(c['rows'])} {kind} vectors, model==engine" if not bad and not loud else
               f"{len(bad)} of {len(c['rows'])} {kind} vectors engine!=model, {len(loud)} not settled")
        msg += f"; engine vs spec: {'agree' if not spec_bad else f'DIFFER on {len(spec_bad)}'}"
        by_part = {}
        if not exhaustive:  # which part of the sampled set sees engine != spec (rows: structured first)
            sv = {row["in"] for row in c["rows"][:nstruct]}
            k = sum(1 for row in spec_bad if row["in"] in sv)
            by_part = {"spec_mismatches_by_part": {"structured": k, "random": len(spec_bad) - k}}
        stage(f"cosim_{be}", ok, msg=msg, vectors=len(c["rows"]), exhaustive=exhaustive,
              structured_vectors=nstruct, random_vectors=nrand, **by_part,
              tests_vs_spec_pass=not spec_bad,
              mismatches=[{"in": r_["in"], "engine": r_["out"], "model": model[r_["in"]]} for r_ in bad[:8]],
              spec_mismatches=[{"in": r_["in"], "engine": r_["out"], "spec": spec_tab[r_["in"]]} for r_ in spec_bad[:8]])

    # 8. metrics
    rs = cos.get("redstone", {}).get("rows", [])
    metrics = {
        "blocks": stats["blocks"], "volume": stats["volume"], "bbox": stats["bbox"],
        "components": meta["components"], "by_type": stats["by_type"],
        "critical_path_rt": meta["critical_path_rt"],
        "max_settle_ticks": max((r_["settle_ticks"] for r_ in rs), default=None),
        "glitches": sum(r_["glitches"] for r_ in rs),
    }
    rep["metrics"] = metrics
    print("  metrics: " + ", ".join(f"{k}={v}" for k, v in metrics.items() if k != "by_type"))
    if a.seed:
        sr = run([RSV, "stats", a.seed])
        s = json.loads(sr.stdout)
        rep["vs_seed"] = {"blocks": [s["blocks"], stats["blocks"]], "volume": [s["volume"], stats["volume"]]}
        print(f"  vs seed: blocks {s['blocks']} -> {stats['blocks']}, volume {s['volume']} -> {stats['volume']}")
    finish()


if __name__ == "__main__":
    main()
