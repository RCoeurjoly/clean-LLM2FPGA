def run(cmd, **kw):
    return subprocess.run(cmd, capture_output=True, text=True, **kw)


def clean(work):
    """Remove artifacts of an earlier run so that no stage can pick up a stale file."""
    for f in ARTIFACTS:
        p = os.path.join(work, f)
        if os.path.exists(p):
            os.remove(p)
    for pat in ("tb_*.v", "sim_*", "vectors_*.hex"):
        for p in glob.glob(os.path.join(work, pat)):
            os.remove(p)
    shutil.rmtree(os.path.join(work, "v2lean"), ignore_errors=True)


def miter_text(top, ins, outs):
    """Miter of spec `top` (gold) and the model rs_impl (gate): _rsv_bad = 1 iff an output differs."""
    conn = lambda pre: ", ".join([f".{p}({p})" for p in ins] + [f".{o}(_rsv_{pre}_{o})" for o in outs])
    s = f"module _rsv_miter({', '.join([f'input {p}' for p in ins] + ['output _rsv_bad'])});\n"
    for o in outs:
        s += f"  wire _rsv_g_{o}, _rsv_i_{o};\n"
    s += f"  {top} _rsv_gold({conn('g')});\n  rs_impl _rsv_gate({conn('i')});\n"
    return s + "  assign _rsv_bad = " + " | ".join(f"(_rsv_g_{o} != _rsv_i_{o})" for o in outs) + ";\nendmodule\n"


def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def tool_versions():
    """Versions and hashes of the tools and scripts a certificate depends on."""
    def first_line(cmd):
        try:
            r = run(cmd)
            return ((r.stdout or r.stderr).strip().splitlines() or [None])[0]
        except OSError:
            return None

    def h(p):
        return sha256(p) if os.path.isfile(p) else None

    def read(p, pat):
        try:
            m = re.search(pat, open(p).read())
            return m.group(1) if m else None
        except OSError:
            return None
    dt = os.path.dirname(LRAT_CHECK)
    return {
        "yosys": first_line(["yosys", "-V"]),
        "cadical": {"path": shutil.which(CADICAL), "version": first_line([CADICAL, "--version"])},
        "lrat_check": {"path": LRAT_CHECK, "sha256": h(LRAT_CHECK), "source_sha256": h(LRAT_CHECK + ".c"),
                       "drat_trim_commit": read(os.path.join(dt, ".git", "HEAD"), r"^([0-9a-f]{40})")},
        "cake_lpr": {"path": CAKE_LPR, "sha256": h(CAKE_LPR)},
        "rsv": {"sha256": h(RSV), "mchprs_rev": read(os.path.join(ROOT, "rsv", "Cargo.toml"), r'rev = "([0-9a-f]+)"')},
        "python": sys.version.split()[0],
        "scripts_sha256": {f: h(os.path.join(ROOT, "tools", f))
                           for f in ("verify.py", "graph2v.py", "aig2cnf.py", "check_cert.py", "v2lean.py",
                                     "graph2lean.py")},
        "lean_toolchain": read(os.path.join(LEAN_DIR, "lean-toolchain"), r"(\S+)"),
    }


def aig_cone(I, ands, out):
    """(AND gates, inputs) in the transitive fan-in of the output literal."""
    gate = {lhs // 2: (r0 // 2, r1 // 2) for lhs, r0, r1 in ands}
    seen, todo = set(), [out // 2]
    while todo:
        v = todo.pop()
        if v not in seen:
            seen.add(v)
            todo += gate.get(v, ())
    return sum(v in gate for v in seen), sum(1 <= v <= I for v in seen)


def read_cnf(path):
    with open(path) as f:
        toks = [int(t) for line in f if not line.startswith(("c", "p")) for t in line.split()]
    clauses, cur = [], []
    for t in toks:
        if t:
            cur.append(t)
        else:
            clauses.append(cur)
            cur = []
    return clauses


def unit_refutes(clauses):
    """True if unit propagation alone derives a conflict, i.e. the refutation is trivial."""
    true, occ = set(), defaultdict(list)
    for c in clauses:
        for l in c:
            occ[-l].append(c)          # occ[x]: clauses to revisit once x becomes true
    todo = list(clauses)
    while todo:
        c = todo.pop()
        if any(l in true for l in c):
            continue
        free = {l for l in c if -l not in true}
        if not free:
            return True
        if len(free) == 1:
            l = free.pop()
            true.add(l)
            todo += occ[l]
    return False


def certify(work, top, ins, outs, inputs_sha256):
    """Stage 5 -> (ok, msg, info, certificate or None). Each step checks its return code, and its
    output file is deleted before the step runs, so only a file written by this run is ever read.
    `inputs_sha256`: hashes of the layout/spec bytes read at start-up, which the copies must match."""
    P = lambda f: os.path.join(work, f)
    t = {}
    info = {"step_time_s": t}          # filled in step by step, also when a step fails

    def step(name, cmd, outfile, log):
        for f in (outfile, log):
            if os.path.exists(P(f)):
                os.remove(P(f))
        t0 = time.perf_counter()
        try:
            r = run(cmd, cwd=work)
        except OSError as e:
            r = subprocess.CompletedProcess(cmd, 127, "", str(e))
        t[name] = round(time.perf_counter() - t0, 4)
        if name != "yosys":                       # yosys writes its own log (-l)
            open(P(log), "w").write(r.stdout + r.stderr)
        return r, os.path.isfile(P(outfile)) and os.path.getsize(P(outfile)) > 0

    open(P("aiger.ys"), "w").write(AIGER_SCRIPT)
    open(P("divzero_map.v"), "w").write(DIVZERO_MAP)
    r, made = step("yosys", ["yosys", "-q", "-e", FATAL_WARNINGS, "-l", "aiger.log", "aiger.ys"], "miter.aag",
                   "aiger.log")
    if r.returncode or not made:
        log = (open(P("aiger.log")).read() if os.path.exists(P("aiger.log")) else r.stderr).splitlines()
        err = next((l.strip() for l in log if "ERROR" in l), f"yosys rc={r.returncode}")
        why = next((l.strip() for l in log if l.startswith("Warning: found logic loop")), None)
        return False, "AIGER export failed: " + err + (f" ({why})" if why else ""), info, None
    r, made = step("aig2cnf", [sys.executable, AIG2CNF, "miter.aag", "miter.cnf"], "miter.cnf", "aig2cnf.log")
    if r.returncode or not made:
        return False, "Tseitin encoding failed: " + (r.stderr.strip().splitlines() or [f"rc={r.returncode}"])[-1], info, None
    enc = json.loads(r.stdout)
    named = [v for k, v in sorted(enc["symbols"].items()) if k[0] == "i"]
    if enc["symbols"].get("o0") != "_rsv_bad" or sorted(named) != sorted(ins):
        return False, f"AIGER is not the miter: output {enc['symbols'].get('o0')}, named inputs {named}", info, None
    info.update(cnf=[str(enc["vars"]), str(enc["clauses"])], aig_ands=enc["ands"])
    # Pin every bound file before the untrusted solver runs; it may write only miter.lrat.
    pinned = {f: sha256(P(f)) for f in BOUND if f != "miter.lrat"}
    r, made = step("cadical", [CADICAL, "--lrat", "--no-binary", "-q", "miter.cnf", "miter.lrat"], "miter.lrat",
                   "cadical.log")
    if r.returncode == 10:
        return False, "CNF is SAT (not equivalent)", info, None
    if r.returncode != 20 or not made:
        return False, f"no LRAT proof (cadical rc={r.returncode}, proof file {'written' if made else 'missing'})", info, None
    info.update(proof_bytes=os.path.getsize(P("miter.lrat")))
    checkers, rejected, verdicts = run_checkers(P("miter.cnf"), P("miter.lrat"), work, t)
    info.update(checkers=verdicts)
    if rejected:                       # every checker that ran must accept
        return False, "LRAT proof rejected by " + "; ".join(f"{k}: {verdicts[k]}" for k in rejected), info, None
    changed = [f for f in pinned if sha256(P(f)) != pinned[f]] + \
              [f for f, h in inputs_sha256.items() if pinned[f] != h]
    if changed:
        return False, f"files changed behind the funnel's back (e.g. by the solver): {changed}", info, None

    # Everything below only describes the certificate; the verdict above does not depend on it.
    M, I, ands, out, symbols = aig2cnf.parse(open(P("miter.aag"), encoding="ascii").read())
    lemmas = deletions = 0
    with open(P("miter.lrat")) as f:
        for line in f:
            tok = line.split(None, 2)
            deletions += len(tok) > 1 and tok[1] == "d"
            lemmas += len(tok) > 1 and tok[1] != "d"
    cone_ands, cone_inputs = aig_cone(I, ands, out)
    trivial = {"aig_output_constant": out < 2, "cone_has_no_and_gate": cone_ands == 0,
               "unit_propagation_refutes_cnf": unit_refutes(read_cnf(P("miter.cnf")))}
    cert = {
        "format": "redstone-pce certificate v1 (docs/CERTIFICATE.md)",
        "claim": f"miter.aag has output _rsv_bad = 0 under all 2^{I} assignments to its {I} inputs "
                 f"({len(named)} spec inputs, {I - len(named)} free values of x/undriven bits)",
        "top": top, "inputs": ins, "outputs": outs,
        "sha256": dict(pinned, **{"miter.lrat": sha256(P("miter.lrat"))}),
        "derivation": [
            f"cp <layout> {LAYOUT_COPY}; cp <spec> {SPEC_COPY}",
            f"rsv graph {LAYOUT_COPY} > graph.json",
            "graph2v.py graph.json rs_impl meta.json > impl.v",
            "miter.v = verify.miter_text(top, inputs, outputs)",
            f"yosys -q -e '{FATAL_WARNINGS}' aiger.ys  (reads divzero_map.v, writes miter.aag)",
            "aig2cnf.py miter.aag miter.cnf",
            "cadical --lrat --no-binary miter.cnf miter.lrat  (untrusted)",
            "checkers on (miter.cnf, miter.lrat): check_cert.rup_check; lrat-check; cake_lpr (all must accept)",
        ],
        "aig": {"inputs": I, "spec_inputs": len(named), "free_inputs": I - len(named), "ands": len(ands),
                "cone_ands": cone_ands, "cone_inputs": cone_inputs, "output_literal": out},
        "cnf": {"vars": enc["vars"], "clauses": enc["clauses"]},
        "lrat": {"bytes": os.path.getsize(P("miter.lrat")), "lemmas": lemmas, "deletions": deletions},
        "trivial": trivial,
        "checkers": verdicts,
        "step_time_s": t,
        "tools": tool_versions(),
    }
    info.update(aig_cone_ands=cone_ands, lrat_lemmas=lemmas, trivial=any(trivial.values()))
    return True, "LRAT proof checked by " + ", ".join(checkers), info, cert


def run_checkers(cnf, lrat, work, t):
    """Check the LRAT proof with every available checker -> (accepted, rejected, {name: verdict}).
    rup_check (tools/check_cert.py), lrat-check and cake_lpr (verified) all run and all must accept;
    a missing cake_lpr is a rejection, never a pass.
    Output files are produced by this run only (the caller deleted them before CaDiCaL ran)."""
    ok, bad, verdicts = [], [], {}
    t0 = time.perf_counter()
    good, msg = check_cert.rup_check(open(cnf).read(), open(lrat).read())
    t["rup_check"] = round(time.perf_counter() - t0, 4)
    verdicts["rup_check"] = msg
    (ok if good else bad).append("rup_check")
    tools = [("lrat-check", [LRAT_CHECK, cnf, lrat], "c VERIFIED"),
             ("cake_lpr", [CAKE_LPR, cnf, lrat], "s VERIFIED UNSAT")]
    for name, cmd, want in tools:
        if not os.path.isfile(cmd[0]):
            verdicts[name] = f"missing {cmd[0]}: required, build it with `make {'cake_lpr' if name == 'cake_lpr' else 'setup'}`"
            bad.append(name)
            continue
        t0 = time.perf_counter()
        try:
            r = run(cmd, cwd=work)
        except OSError as e:
            r = subprocess.CompletedProcess(cmd, 127, "", str(e))
        t[name] = round(time.perf_counter() - t0, 4)
        open(os.path.join(work, name + ".log"), "w").write(r.stdout + r.stderr)
        # both print their verdict as an exact stdout line; cake_lpr exits 0 even when it rejects
        good = r.returncode == 0 and want in r.stdout.splitlines()
        verdicts[name] = want if good else f"rejected (rc={r.returncode}): " + \
            ((r.stdout + r.stderr).strip().splitlines() or ["no output"])[-1][:120]
        (ok if good else bad).append(name)
    return ok, bad, verdicts


