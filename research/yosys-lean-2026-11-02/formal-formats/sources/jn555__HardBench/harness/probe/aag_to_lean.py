#!/usr/bin/env python3
"""WS3 PROBE (Path B, fallback): translate a combinational (post-aigunroll,
L=0, O=1) ASCII AIGER (.aag) file into a Lean 4 theorem statement of the form

    theorem <name> (i0 : Bool) (i1 : Bool) ... : (<gate chain>) = false := by bv_decide

i.e. "the AIG's single output can never be driven high by any input
assignment" -- the direct BitVec/Bool restatement of the external CaDiCaL
UNSAT verdict on the same combinational circuit (Tseitin-CNF via aigtocnf).
This is the fallback Lean-ingestion path from spec-week1.md SS WS3 Path B,
used because Lean core's LRAT checker has no external-file entry point and
LRAT-Catcher (arXiv 2607.00815) has no public artifact (checked 2026-07-20).

Usage: aag_to_lean.py <in.aag> <out.lean> <theorem_name> [--expect-sat]
"""
import sys


def parse_aag(path):
    with open(path) as f:
        lines = f.read().splitlines()
    header = lines[0].split()
    assert header[0] == "aag", f"not an aag file: {header}"
    M, I, L, O, A = map(int, header[1:6])
    idx = 1
    inputs = []
    for _ in range(I):
        inputs.append(int(lines[idx]))
        idx += 1
    latches = []
    for _ in range(L):
        latches.append(lines[idx].split())
        idx += 1
    outputs = []
    for _ in range(O):
        outputs.append(int(lines[idx]))
        idx += 1
    ands = []
    for _ in range(A):
        parts = lines[idx].split()
        idx += 1
        ands.append((int(parts[0]), int(parts[1]), int(parts[2])))
    return M, I, L, O, A, inputs, latches, outputs, ands


def gen_lean(in_path, out_path, thm_name, expect_sat=False):
    M, I, L, O, A, inputs, latches, outputs, ands = parse_aag(in_path)
    if L != 0:
        raise ValueError(f"expected combinational AIG (L=0), got L={L}")
    if O != 1:
        raise ValueError(f"expected single output (O=1), got O={O}")

    var_name = {}
    for i, lit in enumerate(inputs):
        v = lit >> 1
        assert lit & 1 == 0, "input literal must be positive"
        var_name[v] = f"i{i}"

    def lit_expr(lit):
        if lit == 0:
            return "false"
        if lit == 1:
            return "true"
        v = lit >> 1
        neg = lit & 1
        name = var_name[v]
        return f"(!{name})" if neg else name

    gate_lines = []
    for (lhs, r0, r1) in ands:
        assert lhs & 1 == 0, "AND lhs must be a positive literal"
        v = lhs >> 1
        e0 = lit_expr(r0)
        e1 = lit_expr(r1)
        gate_lines.append(f"  let g{v} := {e0} && {e1}")
        var_name[v] = f"g{v}"

    out_expr = lit_expr(outputs[0])
    params = " ".join(f"(i{i} : Bool)" for i in range(I)) if I > 0 else ""
    rhs_const = "true" if expect_sat else "false"

    with open(out_path, "w") as f:
        f.write("-- AUTO-GENERATED by harness/probe/aag_to_lean.py -- do not hand-edit.\n")
        f.write(f"-- source AIG: {in_path}  (M={M} I={I} L={L} O={O} A={A})\n")
        f.write("import Std.Tactic.BVDecide\n\n")
        f.write("set_option maxRecDepth 4000000\n")
        # Default maxHeartbeats (200000) is not enough to elaborate/bitblast
        # a flat let-chain of O(1e5) AND-gates; disable it and rely on the
        # harness's own 30-min external process timeout as the real cap
        # (this matches the PROBE's intended kill switch, see spec-week1.md
        # SS WS3 / PROBE.md notes).
        f.write("set_option maxHeartbeats 0\n\n")
        sig = f"theorem {thm_name} {params} :".replace("  ", " ")
        f.write(sig + "\n")
        f.write("  (\n")
        for gl in gate_lines:
            f.write(gl + "\n")
        f.write(f"  {out_expr}) = {rhs_const} := by bv_decide\n")


if __name__ == "__main__":
    if len(sys.argv) < 4:
        print(__doc__)
        sys.exit(1)
    in_path, out_path, thm_name = sys.argv[1:4]
    expect_sat = "--expect-sat" in sys.argv[4:]
    gen_lean(in_path, out_path, thm_name, expect_sat=expect_sat)
    print(f"wrote {out_path}")
